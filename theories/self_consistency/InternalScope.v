(** Both observations have exactly the Index motive rank, so there is no
    implicit lifting of an eliminator and no cumulative universe coercion. *)
Definition index_guard_type (input : bool) := close
  (npis [(0, C); (1, C); (2, Index (NVar 0) (NVar 1))]
    (Num (NVar (if input then 0 else 1))))
  (ltac:(destruct input; reflexivity)).
Definition index_guard_zero (input : bool) :=
  nlams [(10, C); (11, C); (14, Succ (NVar 10) (NVar 11))]
    (if input then napps (NClosed succ_output) [NVar 10; NVar 11; NVar 14]
     else NClosed num_zero).
Definition index_guard_step (input : bool) :=
  nlams [(10, C); (11, C); (12, C); (13, C);
    (14, Num (NVar (if input then 10 else 11)));
    (15, Succ (NVar 10) (NVar 12)); (16, Succ (NVar 11) (NVar 13))]
    (napps (NClosed succ_output)
      [NVar (if input then 10 else 11); NVar (if input then 12 else 13);
       NVar (if input then 15 else 16)]).
Definition index_guard (input : bool) := close
  (nlams [(0, C); (1, C); (2, Index (NVar 0) (NVar 1))]
    (napps (NVar 2) [nlams [(10, C); (11, C)]
      (Num (NVar (if input then 10 else 11)));
      index_guard_zero input; index_guard_step input]))
  (ltac:(destruct input; reflexivity)).
Definition index_input_num := index_guard true.
Definition index_output_num := index_guard false.
Theorem index_guard_type_sorted input : Typed ε (index_guard_type input) (𝓤 11).
Proof. destruct input; RkCheck.certify_with 512. Qed.
Theorem index_guard_typed input : Typed ε (index_guard input) (index_guard_type input).
Proof. destruct input; RkCheck.certify_with 4096. Qed.

