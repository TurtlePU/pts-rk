(** Index(n,i) is generated by zero below a successor, and by simultaneous
    successor of a previously generated bound/index pair. Binary carry is
    supplied by the independent successor relation, not assumed arithmetic. *)
Definition IR n i := napps (NVar 50) [n; i].
Definition index_zero_rule := npis [(10, C); (11, C); (14, Succ (NVar 10) (NVar 11))]
  (IR (NVar 11) stop).
Definition index_step_rule := npis [(10, C); (11, C); (12, C); (13, C);
  (14, IR (NVar 10) (NVar 11)); (15, Succ (NVar 10) (NVar 12));
  (16, Succ (NVar 11) (NVar 13))] (IR (NVar 12) (NVar 13)).
Definition index_fields := [(50, nArrow C (nArrow C (NSort 6)));
  (51, index_zero_rule); (52, index_step_rule)].
Definition index := close (nlams [(0, C); (1, C)]
  (npis index_fields (IR (NVar 0) (NVar 1)))) eq_refl.
Definition Index n i := napps (NClosed index) [n; i].

Definition index_zero_type := close
  (npis [(0, C); (1, C); (2, Succ (NVar 0) (NVar 1))]
    (Index (NVar 1) stop)) eq_refl.
Definition index_zero := close
  (nlams ([(0, C); (1, C); (2, Succ (NVar 0) (NVar 1))] ++ index_fields)
    (napps (NVar 51) [NVar 0; NVar 1; NVar 2])) eq_refl.
Definition index_step_type := close
  (npis [(0, C); (1, C); (2, C); (3, C);
    (4, Index (NVar 0) (NVar 1)); (5, Succ (NVar 0) (NVar 2));
    (6, Succ (NVar 1) (NVar 3))] (Index (NVar 2) (NVar 3))) eq_refl.
Definition index_step := close
  (nlams ([(0, C); (1, C); (2, C); (3, C);
    (4, Index (NVar 0) (NVar 1)); (5, Succ (NVar 0) (NVar 2));
    (6, Succ (NVar 1) (NVar 3))] ++ index_fields)
    (napps (NVar 52) [NVar 0; NVar 1; NVar 2; NVar 3;
      napps (NVar 4) [NVar 50; NVar 51; NVar 52]; NVar 5; NVar 6])) eq_refl.

