(** Scope entails raw structural generation by its exact rank-4 fold.
    This does not establish source typing, substitution preservation, or
    canonical reflection of arbitrary internal scope witnesses. *)
Definition generated_node a b ga gb := napps (NClosed good_pair) [a; b; ga; gb].
Definition generated_unary tag a ga :=
  generated_node (NClosed (atom tag)) a (NClosed (good_atom tag)) ga.
Definition generated_binary tag a b ga gb :=
  generated_unary tag (node a b) (generated_node a b ga gb).
Definition scope_generation_sort := nlams [(10, C); (11, C);
  (14, Num (NVar 10)); (15, Num (NVar 11))]
  (generated_unary TSort (NVar 11) (napps (NClosed num_generation) [NVar 11; NVar 15])).
Definition scope_generation_var := nlams [(10, C); (11, C);
  (14, Index (NVar 10) (NVar 11))]
  (generated_unary TVar (NVar 11) (napps (NClosed num_generation)
    [NVar 11; napps (NClosed index_output_num) [NVar 10; NVar 11; NVar 14]])).
Definition scope_generation_binder tag := nlams [(10, C); (11, C); (12, C); (13, C);
  (14, Succ (NVar 10) (NVar 11)); (15, G (NVar 12)); (16, G (NVar 13))]
  (generated_binary tag (NVar 12) (NVar 13) (NVar 15) (NVar 16)).
Definition scope_generation_app := nlams [(10, C); (12, C); (13, C);
  (15, G (NVar 12)); (16, G (NVar 13))]
  (generated_binary TApp (NVar 12) (NVar 13) (NVar 15) (NVar 16)).
Definition scope_generation_type := close
  (npis [(0, C); (1, C); (2, Scope (NVar 0) (NVar 1))] (G (NVar 1))) eq_refl.
Definition scope_generation := close
  (nlams [(0, C); (1, C); (2, Scope (NVar 0) (NVar 1))]
    (napps (NVar 2) [nlams [(10, C); (11, C)] (G (NVar 11));
      scope_generation_sort; scope_generation_var;
      scope_generation_binder TPi; scope_generation_binder TLam; scope_generation_app])) eq_refl.
Theorem scope_generation_type_sorted : Typed ε scope_generation_type (𝓤 13).
Proof. RkCheck.certify_with 1024. Qed.
Theorem scope_generation_typed : Typed ε scope_generation scope_generation_type.
Proof. RkCheck.certify_with 8192. Qed.

