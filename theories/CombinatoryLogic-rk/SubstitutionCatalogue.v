From Stdlib Require Import Arith.PeanoNat Lia.
From PTSrk Require Import Syntax Context Typing Ranks.
From PTSrk.Combinatory Require Import Core ProductCatalogue.

(** The dependent-S part of the Bunder--Dekkers finite Hilbert catalogue,
    generated by type formation and product exposure (Definition 7.3).
    There are thirty new shapes: the original S, seven exposures of its
    type, and twenty-two sort-ended telescope prefixes of lengths 3--6.
    The five shorter sort-ended prefixes are already product schemes.
    The only scheme parameters are numbers; no source term or target typing
    judgement is an admission parameter.  This is a catalogue and closure
    result, not a proof of Hilbert completeness. *)
Module SubstitutionCatalogue.

Local Abbreviation v0 := (var fzero).
Local Abbreviation v1 := (var (fsucc fzero)).
Local Abbreviation v2 := (var (fsucc (fsucc fzero))).
Local Abbreviation v3 := (var (fsucc (fsucc (fsucc fzero)))).
Local Abbreviation v4 := (var (fsucc (fsucc (fsucc (fsucc fzero))))).

Inductive Shape : Type :=
| S1
| S2 | S3 | S4 | S5 | S6 | S7 | S8
| S9 | S10 | S11 | S12
| S13 | S14 | S15 | S16 | S17
| S18 | S19 | S20 | S21 | S22 | S23
| S24 | S25 | S26 | S27 | S28 | S29 | S30.

Record Scheme : Type := make {
  shape : Shape;
  domain_rank : nat;
  family_rank : nat;
  result_rank : nat;
  final_sort : nat
}.

(** Fixed prefixes of the six-argument S telescope.  [e] is the number of
    initial lambdas, with the remaining nodes products.  These builders
    merely factor the thirty fixed syntax shapes; arbitrary bodies never
    occur in the scheme datatype. *)
Definition binder {n} e (A : Term nat n) (B : Term nat (S n)) : Term nat n :=
  match e with 0 => Π A B | S _ => lam A B end.

Definition prefix1 {n} e a (body : Term nat (S n)) : Term nat n :=
  binder e (𝓤 a) body.
Definition prefix2 {n} e a b (body : Term nat (S (S n))) : Term nat n :=
  prefix1 e a (binder (Nat.pred e) (Π v0 (𝓤 b)) body).
Definition prefix3 {n} e a b c (body : Term nat (S (S (S n)))) : Term nat n :=
  prefix2 e a b
    (binder (e - 2) (Π v1 (Π (v1 $ v0) (𝓤 c))) body).
Definition prefix4 {n} e a b c (body : Term nat (S (S (S (S n))))) : Term nat n :=
  prefix3 e a b c
    (binder (e - 3) (Π v2 (Π (v2 $ v0) (v2 $ v1 $ v0))) body).
Definition prefix5 {n} e a b c (body : Term nat (S (S (S (S (S n)))))) : Term nat n :=
  prefix4 e a b c (binder (e - 4) (Π v3 (v3 $ v0)) body).
Definition prefix6 {n} e a b c (body : Term nat (S (S (S (S (S (S n))))))) : Term nat n :=
  prefix5 e a b c (binder (e - 5) v4 body).

Definition ground_prefix {n} k e a b c d : Term nat n :=
  match k with
  | 0 => 𝓤 d
  | 1 => prefix1 e a (𝓤 d)
  | 2 => prefix2 e a b (𝓤 d)
  | 3 => prefix3 e a b c (𝓤 d)
  | 4 => prefix4 e a b c (𝓤 d)
  | 5 => prefix5 e a b c (𝓤 d)
  | _ => prefix6 e a b c (𝓤 d)
  end.

(** The rank of each ORIGINAL binder domain, in telescope order. *)
Definition binder_rank a b c i :=
  match i with
  | 0 => 0
  | 1 => Nat.max (S a) 0
  | 2 => Nat.max (S a) (Nat.max (S b) 0)
  | 3 => Nat.max (S a) (Nat.max (S b) c)
  | 4 => Nat.max (S a) b
  | _ => a
  end.

Fixpoint product_rank a b c start count tail : nat :=
  match count with
  | 0 => tail
  | S k => Nat.max (S (binder_rank a b c start))
      (product_rank a b c (S start) k tail)
  end.

Definition length (p : Shape) : nat :=
  match p with
  | S9 | S10 | S11 | S12 => 3
  | S13 | S14 | S15 | S16 | S17 => 4
  | S18 | S19 | S20 | S21 | S22 | S23 => 5
  | _ => 6
  end.

Definition exposure_count (p : Shape) : nat :=
  match p with
  | S3 | S10 | S14 | S19 | S25 => 1
  | S4 | S11 | S15 | S20 | S26 => 2
  | S5 | S12 | S16 | S21 | S27 => 3
  | S6 | S17 | S22 | S28 => 4
  | S7 | S23 | S29 => 5
  | S8 | S30 => 6
  | _ => 0
  end.

Definition is_type_body (p : Shape) : bool :=
  match p with S2 | S3 | S4 | S5 | S6 | S7 | S8 => true | _ => false end.

Definition subject {n} (s : Scheme) : Term nat n :=
  let '(make p a b c d) := s in
  match p with
  | S1 => Core.substitution a b c
  | _ =>
      if is_type_body p then
        prefix6 (exposure_count p) a b c (v3 $ v0 $ (v1 $ v0))
      else ground_prefix (length p) (exposure_count p) a b c d
  end.

Definition declared_type {n} (s : Scheme) : Term nat n :=
  let '(make p a b c _) := s in
  match p with
  | S1 => Core.substitution_type a b c
  | _ => ground_prefix (exposure_count p) 0 a b c
      (product_rank a b c (exposure_count p) (length p - exposure_count p)
        (if is_type_body p then c else 0))
  end.

Definition type_rank (s : Scheme) : nat :=
  let '(make p a b c _) := s in
  match p with
  | S1 => product_rank a b c 0 6 c
  | _ => product_rank a b c 0 (exposure_count p) 0
  end.

(** This tactic only composes the original six typing constructors. *)
Local Ltac infer_original G t :=
  lazymatch t with
  | 𝓤 ?a => constr:(@typ_𝓤 nat RankSorts _ G a 0 eq_refl)
  | var ?i => constr:(@typ_var nat RankSorts _ G i)
  | Π ?A ?B =>
      let pA := infer_original G A in
      let pB := infer_original (G & A) B in
      let TA := type of pA in let TA := eval cbn - [Nat.max] in TA in
      let TB := type of pB in let TB := eval cbn - [Nat.max] in TB in
      lazymatch TA with
      | @typ _ _ _ _ _ (𝓤 ?a) =>
          lazymatch TB with
          | @typ _ _ _ _ _ (𝓤 ?b) =>
              constr:(@typ_Π nat RankSorts _ G A B a b
                (Nat.max (S a) b) pA pB eq_refl)
          end
      end
  | lam ?A ?b =>
      let pA := infer_original G A in
      let pb := infer_original (G & A) b in
      let TA := type of pA in let TA := eval cbn - [Nat.max] in TA in
      lazymatch TA with
      | @typ _ _ _ _ _ (𝓤 ?a) =>
          constr:(@typ_λ nat RankSorts _ G A b _ a pA pb)
      end
  | app ?f ?x =>
      let pf := infer_original G f in
      let px := infer_original G x in
      let Tf := type of pf in let Tf := eval cbn - [Nat.max] in Tf in
      lazymatch Tf with
      | @typ _ _ _ _ _ (Π ?A ?B) =>
          constr:(@typ_app nat RankSorts _ G f B x A pf px)
      end
  end.

Local Ltac expand_shape t :=
  eval cbv beta delta [subject declared_type Core.substitution
    Core.substitution_type ground_prefix prefix1 prefix2 prefix3 prefix4
    prefix5 prefix6 binder exposure_count length is_type_body
    Nat.sub Nat.pred] iota zeta in t.

Theorem scheme_typed {n} (G : Ctx nat n) s :
  @typ nat RankSorts n G (subject s) (declared_type s).
Proof.
  destruct s as [p a b c d]. destruct p;
  lazymatch goal with
  | |- @typ _ _ _ ?G ?t _ =>
      let t := expand_shape t in
      let p := infer_original G t in exact p
  end.
Qed.

Theorem scheme_type_sorted {n} (G : Ctx nat n) s :
  @typ nat RankSorts n G (declared_type s) (𝓤 (type_rank s)).
Proof.
  destruct s as [p a b c d]. destruct p;
  lazymatch goal with
  | |- @typ _ _ _ ?G ?t _ =>
      let t := expand_shape t in
      let p := infer_original G t in exact p
  end.
Qed.

(** Type-formation closure uses the five already available short product
    shapes rather than duplicating them as new S atoms. *)
Inductive TypeCode : Type :=
| SortCode (a : nat)
| ProductCode (s : ProductCatalogue.Scheme)
| SchemeCode (s : Scheme).

Definition ground_code k a b c d : TypeCode :=
  match k with
  | 0 => SortCode d
  | 1 => ProductCode (ProductCatalogue.P5 a d)
  | 2 => ProductCode (ProductCatalogue.P2 a b d)
  | 3 => SchemeCode (make S9 a b c d)
  | 4 => SchemeCode (make S13 a b c d)
  | 5 => SchemeCode (make S18 a b c d)
  | _ => SchemeCode (make S24 a b c d)
  end.

Definition type_code (s : Scheme) : TypeCode :=
  let '(make p a b c d) := s in
  match p with
  | S1 => SchemeCode (make S2 a b c d)
  | _ => ground_code (exposure_count p) a b c
      (product_rank a b c (exposure_count p) (length p - exposure_count p)
        (if is_type_body p then c else 0))
  end.

Definition expand_type_code {n} (t : TypeCode) : Term nat n :=
  match t with
  | SortCode a => 𝓤 a
  | ProductCode q => ProductCatalogue.subject q
  | SchemeCode s => subject s
  end.

Definition code_type {n} (t : TypeCode) : Term nat n :=
  match t with
  | SortCode _ => 𝓤 0
  | ProductCode q => ProductCatalogue.declared_type q
  | SchemeCode s => declared_type s
  end.

Theorem type_code_exact {n} s :
  @expand_type_code n (type_code s) = declared_type s.
Proof. destruct s as [p a b c d]. destruct p; reflexivity. Qed.

Theorem type_code_rank_exact {n} s :
  @code_type n (type_code s) = 𝓤 (type_rank s).
Proof.
  destruct s as [p a b c d]. destruct p;
    cbn [code_type type_code ground_code declared_type ground_prefix type_rank
      ProductCatalogue.declared_type product_rank binder_rank exposure_count
      length is_type_body]; try reflexivity; f_equal; lia.
Qed.

(** Every exposure of a leading product has a literal next catalogue shape. *)
Definition next_shape (p : Shape) : option Shape :=
  match p with
  | S2 => Some S3 | S3 => Some S4 | S4 => Some S5
  | S5 => Some S6 | S6 => Some S7 | S7 => Some S8
  | S9 => Some S10 | S10 => Some S11 | S11 => Some S12
  | S13 => Some S14 | S14 => Some S15 | S15 => Some S16 | S16 => Some S17
  | S18 => Some S19 | S19 => Some S20 | S20 => Some S21
  | S21 => Some S22 | S22 => Some S23
  | S24 => Some S25 | S25 => Some S26 | S26 => Some S27
  | S27 => Some S28 | S28 => Some S29 | S29 => Some S30
  | _ => None
  end.

Definition exposure (s : Scheme) : option Scheme :=
  let '(make p a b c d) := s in
  option_map (fun q => make q a b c d) (next_shape p).

Theorem exposure_exact {n} s :
  ProductCatalogue.expose_product (@subject n s) = option_map subject (exposure s).
Proof. destruct s as [p a b c d]. destruct p; reflexivity. Qed.

Theorem substitution_rank_exact a b c d :
  type_rank (make S1 a b c d) =
    Nat.max (S (S a)) (Nat.max (S (S b)) (S c)).
Proof. cbn [type_rank product_rank binder_rank]. lia. Qed.

Print Assumptions scheme_typed.
Print Assumptions scheme_type_sorted.
Print Assumptions type_code_exact.
Print Assumptions type_code_rank_exact.
Print Assumptions exposure_exact.
Print Assumptions substitution_rank_exact.

End SubstitutionCatalogue.
